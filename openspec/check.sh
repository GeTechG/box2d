#!/usr/bin/env bash
# Checks the OpenSpec tree with the pinned CLI (openspec/cli.pin); CI runs it in the `openspec` job.
# Usage: bash openspec/check.sh   (from any directory of the repository)
set -uo pipefail

root=$(git -C "$(dirname "$0")" rev-parse --show-toplevel) || exit 1
cd "$root" || exit 1
pin=$(tr -d '[:space:]' < openspec/cli.pin)
fail=0
bad() { echo "openspec check: $*" >&2; fail=1; }

# The global CLI when it is the pinned version, otherwise the pinned package through npm.
if command -v openspec >/dev/null && [ "$(openspec --version 2>/dev/null)" = "$pin" ]; then
  openspec() { command openspec "$@"; }
else
  openspec() { npm exec --yes --package="@fission-ai/openspec@$pin" -- openspec "$@"; }
fi

# 1. Strict validation of every spec and active change: an error or a warning fails.
openspec validate --all --strict --no-interactive || bad "openspec validate --all --strict failed (see above)"

# 2. No main spec keeps the placeholder Purpose the archive writes.
for spec in openspec/specs/*/spec.md; do
  [ -e "$spec" ] || continue
  purpose=$(awk '/^## Purpose/{f=1; next} /^## /{f=0} f && NF {print; exit}' "$spec")
  case "$purpose" in
    "TBD - created by archiving change"*) bad "$spec: Purpose is the archive placeholder" ;;
  esac
done

# 3. Every active change was created by `openspec new change`.
for change in openspec/changes/*/; do
  [ "$change" = openspec/changes/archive/ ] && continue
  [ -d "$change" ] || continue
  [ -f "$change.openspec.yaml" ] || bad "${change%/}: no .openspec.yaml (create changes with 'openspec new change')"
done

# 4. The committed skills were generated by the pinned version.
for skill in .claude/skills/openspec-*/SKILL.md .agents/skills/openspec-*/SKILL.md; do
  [ -e "$skill" ] || continue
  by=$(sed -n 's/^[[:space:]]*generatedBy:[[:space:]]*"\{0,1\}\([^"]*\)"\{0,1\}[[:space:]]*$/\1/p' "$skill" | head -n1)
  [ "$by" = "$pin" ] || bad "$skill: generatedBy '${by:-none}' is not the pin '$pin' (regenerate with 'openspec update')"
done

# 5. An archived change leaves open only the tasks a human has to do.
while IFS= read -r line; do
  bad "open task in the archive: $line"
done < <(grep -rn --include=tasks.md -E '^[[:space:]]*- \[ \]' openspec/changes/archive 2>/dev/null | grep -v '\[human\]')

if [ "$fail" -ne 0 ]; then
  echo "openspec check: FAILED" >&2
  exit 1
fi
echo "openspec check: OK (OpenSpec $pin)"
